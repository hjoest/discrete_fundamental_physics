"""Exact finite group constructions and structural invariants."""

from __future__ import annotations
from dataclasses import dataclass
from typing import Dict, List, Set, Tuple


@dataclass
class FiniteGroup:
    """Exact representation of a finite group via its Cayley multiplication table.

    Element 0 is always guaranteed to be the identity element e.
    """

    name: str
    order: int
    mult: List[List[int]]
    inv: List[int]
    classes: List[List[int]]
    elem_to_class: List[int]
    elem_orders: List[int]
    commutator_subgroup: List[int]
    abelianization_order: int
    elements_repr: List[object]

    @property
    def num_classes(self) -> int:
        return len(self.classes)

    @property
    def is_perfect(self) -> bool:
        return len(self.commutator_subgroup) == self.order

    @property
    def commuting_probability(self) -> float:
        return len(self.classes) / self.order

    def product(self, seq: List[int] | Tuple[int, ...]) -> int:
        acc = 0
        for g in seq:
            acc = self.mult[acc][g]
        return acc

    def conjugate(self, h: int, g: int) -> int:
        """Return h * g * h^{-1}."""
        return self.mult[self.mult[h][g]][self.inv[h]]


def build_group_from_table(
    name: str, elements: List[object], mul_fn
) -> FiniteGroup:
    """Construct a FiniteGroup from a list of elements (with identity at index 0) and a multiplication function."""
    n = len(elements)
    idx_map = {el: i for i, el in enumerate(elements)}
    mult = [[0] * n for _ in range(n)]
    inv = [0] * n

    for i, a in enumerate(elements):
        for j, b in enumerate(elements):
            c = mul_fn(a, b)
            k = idx_map[c]
            mult[i][j] = k
            if k == 0:
                inv[i] = j

    # Conjugacy classes (identity class 0 first)
    visited = [False] * n
    classes: List[List[int]] = []
    elem_to_class = [0] * n
    for g in range(n):
        if not visited[g]:
            c_set = {mult[mult[h][g]][inv[h]] for h in range(n)}
            c_list = sorted(c_set)
            c_idx = len(classes)
            for x in c_list:
                visited[x] = True
                elem_to_class[x] = c_idx
            classes.append(c_list)

    # Element orders
    elem_orders = [1] * n
    for g in range(1, n):
        cur = g
        ord_g = 1
        while cur != 0:
            cur = mult[cur][g]
            ord_g += 1
        elem_orders[g] = ord_g

    # Commutator subgroup [G, G] generated by all g h g^{-1} h^{-1}
    comm_gens: Set[int] = set()
    for g in range(n):
        ig = inv[g]
        for h in range(n):
            ih = inv[h]
            comm = mult[mult[g][h]][mult[ig][ih]]
            comm_gens.add(comm)

    # Subgroup closure of comm_gens
    comm_sub: Set[int] = {0}
    frontier = list(comm_gens)
    while frontier:
        x = frontier.pop()
        if x not in comm_sub:
            comm_sub.add(x)
            for y in list(comm_sub):
                for prod in (mult[x][y], mult[y][x]):
                    if prod not in comm_sub:
                        frontier.append(prod)

    comm_list = sorted(comm_sub)
    ab_order = n // len(comm_list)

    return FiniteGroup(
        name=name,
        order=n,
        mult=mult,
        inv=inv,
        classes=classes,
        elem_to_class=elem_to_class,
        elem_orders=elem_orders,
        commutator_subgroup=comm_list,
        abelianization_order=ab_order,
        elements_repr=elements,
    )


def build_cyclic(n: int) -> FiniteGroup:
    """Cyclic group Z_n of order n."""
    elems = list(range(n))
    return build_group_from_table(f"Z_{n}", elems, lambda a, b: (a + b) % n)


def build_s3() -> FiniteGroup:
    """Symmetric group S_3 of order 6."""
    from itertools import permutations
    elems = list(permutations((0, 1, 2)))
    return build_group_from_table(
        "S_3", elems, lambda a, b: tuple(a[b[i]] for i in range(3))
    )


def build_a4() -> FiniteGroup:
    """Alternating group A_4 of order 12 (tetrahedral rotation group)."""
    from itertools import permutations

    def parity(p):
        inv_cnt = sum(1 for i in range(4) for j in range(i + 1, 4) if p[i] > p[j])
        return inv_cnt % 2 == 0

    elems = [p for p in permutations((0, 1, 2, 3)) if parity(p)]
    return build_group_from_table(
        "A_4", elems, lambda a, b: tuple(a[b[i]] for i in range(4))
    )


def build_sl2_fp(p: int, name: str | None = None) -> FiniteGroup:
    """Special linear group SL(2, F_p) of 2x2 matrices over F_p with det = 1 mod p.

    - p = 3: 2T (Binary tetrahedral group, order 24)
    - p = 5: 2I (Binary icosahedral group / 600-cell vertex group, order 120)
    """
    elems = [
        (a, b, c, d)
        for a in range(p)
        for b in range(p)
        for c in range(p)
        for d in range(p)
        if (a * d - b * c) % p == 1
    ]
    id_el = (1, 0, 0, 1)
    elems.remove(id_el)
    elems.insert(0, id_el)

    def mul_sl2(A, B):
        return (
            (A[0] * B[0] + A[1] * B[2]) % p,
            (A[0] * B[1] + A[1] * B[3]) % p,
            (A[2] * B[0] + A[3] * B[2]) % p,
            (A[2] * B[1] + A[3] * B[3]) % p,
        )

    label = name or f"SL(2, F_{p})"
    return build_group_from_table(label, elems, mul_sl2)


def build_2t() -> FiniteGroup:
    """Binary tetrahedral group 2T ~= SL(2, F_3) of order 24."""
    return build_sl2_fp(3, name="2T")


def build_2o() -> FiniteGroup:
    """Binary octahedral group 2O < SU(2) of order 48 (double cover of S_4)."""
    import itertools
    import math

    s2 = 1.0 / math.sqrt(2.0)
    raw_quats: List[Tuple[float, float, float, float]] = []
    # 8 axis unit quaternions
    for i in range(4):
        for sign in (1.0, -1.0):
            q = [0.0, 0.0, 0.0, 0.0]
            q[i] = sign
            raw_quats.append((q[0], q[1], q[2], q[3]))
    # 16 half-integer unit quaternions (together with 8 axis -> 24 elements of 2T)
    for signs in itertools.product((0.5, -0.5), repeat=4):
        raw_quats.append(signs)
    # 24 face-diagonal unit quaternions (+/- 1/sqrt(2), +/- 1/sqrt(2), 0, 0)
    for i in range(4):
        for j in range(i + 1, 4):
            for s1 in (s2, -s2):
                for s2_val in (s2, -s2):
                    q = [0.0, 0.0, 0.0, 0.0]
                    q[i] = s1
                    q[j] = s2_val
                    raw_quats.append((q[0], q[1], q[2], q[3]))

    def q_key(q: Tuple[float, float, float, float]) -> Tuple[float, float, float, float]:
        return tuple(round(c, 6) + 0.0 for c in q)  # type: ignore

    def q_mul(a: Tuple[float, float, float, float], b: Tuple[float, float, float, float]) -> Tuple[float, float, float, float]:
        return (
            a[0] * b[0] - a[1] * b[1] - a[2] * b[2] - a[3] * b[3],
            a[0] * b[1] + a[1] * b[0] + a[2] * b[3] - a[3] * b[2],
            a[0] * b[2] - a[1] * b[3] + a[2] * b[0] + a[3] * b[1],
            a[0] * b[3] + a[1] * b[2] - a[2] * b[1] + a[3] * b[0],
        )

    id_key = q_key((1.0, 0.0, 0.0, 0.0))
    key_to_q = {q_key(q): q for q in raw_quats}
    keys = [id_key] + [k for k in key_to_q if k != id_key]
    return build_group_from_table(
        "2O",
        keys,
        lambda ka, kb: q_key(q_mul(key_to_q[ka], key_to_q[kb])),
    )


def build_2i() -> FiniteGroup:
    """Binary icosahedral group 2I ~= SL(2, F_5) of order 120 (vertices of the 600-cell)."""
    return build_sl2_fp(5, name="2I")


def build_t7() -> FiniteGroup:
    """Frobenius group T_7 = Z_7 \\rtimes Z_3 of order 21 in SU(3)."""
    elems = [(a, b) for a in range(7) for b in range(3)]

    def mul_t7(x, y):
        a1, b1 = x
        a2, b2 = y
        return ((a1 + pow(2, b1, 7) * a2) % 7, (b1 + b2) % 3)

    return build_group_from_table("T_7", elems, mul_t7)


def build_m27() -> FiniteGroup:
    """Extraspecial group M_27 = Z_9 \\rtimes Z_3 of order 27 (exponent 9) in SU(3)."""
    elems = [(a, b) for a in range(9) for b in range(3)]

    def mul_m27(x, y):
        a1, b1 = x
        a2, b2 = y
        return ((a1 + pow(4, b1, 9) * a2) % 9, (b1 + b2) % 3)

    return build_group_from_table("M_27", elems, mul_m27)


def build_psl2_7() -> FiniteGroup:
    """Klein quartic / Fano plane group PSL(2, F_7) ~= GL(3, F_2) of order 168."""
    elems = []
    for bits in range(512):
        m = tuple((bits >> i) & 1 for i in range(9))
        det = (
            m[0] * (m[4] * m[8] ^ m[5] * m[7])
            ^ m[1] * (m[3] * m[8] ^ m[5] * m[6])
            ^ m[2] * (m[3] * m[7] ^ m[4] * m[6])
        )
        if det == 1:
            elems.append(m)
    id_el = (1, 0, 0, 0, 1, 0, 0, 0, 1)
    elems.remove(id_el)
    elems.insert(0, id_el)

    def mul_gl3_2(A, B):
        return (
            (A[0] & B[0]) ^ (A[1] & B[3]) ^ (A[2] & B[6]),
            (A[0] & B[1]) ^ (A[1] & B[4]) ^ (A[2] & B[7]),
            (A[0] & B[2]) ^ (A[1] & B[5]) ^ (A[2] & B[8]),
            (A[3] & B[0]) ^ (A[4] & B[3]) ^ (A[5] & B[6]),
            (A[3] & B[1]) ^ (A[4] & B[4]) ^ (A[5] & B[7]),
            (A[3] & B[2]) ^ (A[4] & B[5]) ^ (A[5] & B[8]),
            (A[6] & B[0]) ^ (A[7] & B[3]) ^ (A[8] & B[6]),
            (A[6] & B[1]) ^ (A[7] & B[4]) ^ (A[8] & B[7]),
            (A[6] & B[2]) ^ (A[7] & B[5]) ^ (A[8] & B[8]),
        )

    return build_group_from_table("PSL(2, F_7)", elems, mul_gl3_2)


def build_delta27() -> FiniteGroup:
    """Discrete Heisenberg group Delta(27) ~= (Z_3 x Z_3) \\rtimes Z_3 of order 27 in SU(3)."""
    elems = [(a, b, c) for a in range(3) for b in range(3) for c in range(3)]

    def mul_d27(x, y):
        return (
            (x[0] + y[0]) % 3,
            (x[1] + y[1]) % 3,
            (x[2] + y[2] + x[0] * y[1]) % 3,
        )

    return build_group_from_table("Delta(27)", elems, mul_d27)


def build_sigma216() -> FiniteGroup:
    """Hessian group Sigma(216) ~= (Z_3 x Z_3) \\rtimes SL(2, F_3) of order 216."""
    sl2_3 = [
        (a, b, c, d)
        for a in range(3)
        for b in range(3)
        for c in range(3)
        for d in range(3)
        if (a * d - b * c) % 3 == 1
    ]
    sl2_3.remove((1, 0, 0, 1))
    sl2_3.insert(0, (1, 0, 0, 1))
    elems = [((v0, v1), M) for v0 in range(3) for v1 in range(3) for M in sl2_3]

    def mul_s216(x, y):
        v, M = x
        w, N = y
        u0 = (v[0] + M[0] * w[0] + M[1] * w[1]) % 3
        u1 = (v[1] + M[2] * w[0] + M[3] * w[1]) % 3
        P = (
            (M[0] * N[0] + M[1] * N[2]) % 3,
            (M[0] * N[1] + M[1] * N[3]) % 3,
            (M[2] * N[0] + M[3] * N[2]) % 3,
            (M[2] * N[1] + M[3] * N[3]) % 3,
        )
        return ((u0, u1), P)

    return build_group_from_table("Sigma(216)", elems, mul_s216)


def _build_su3_matrix_group(name: str, gens: List[Tuple[Tuple[complex, ...], ...]]) -> FiniteGroup:
    """Build a finite subgroup of SU(3) from 3x3 unitary generator matrices."""

    def mat_mul(A, B):
        return tuple(
            tuple(sum(A[i][k] * B[k][j] for k in range(3)) for j in range(3))
            for i in range(3)
        )

    def mat_key(A):
        return tuple(
            tuple((round(x.real, 5) + 0.0, round(x.imag, 5) + 0.0) for x in row)
            for row in A
        )

    I = ((1 + 0j, 0j, 0j), (0j, 1 + 0j, 0j), (0j, 0j, 1 + 0j))
    seen = {mat_key(I): I}
    elems_mat = [I]
    frontier = [I]
    while frontier:
        cur = frontier.pop()
        for g in gens:
            nxt = mat_mul(cur, g)
            k = mat_key(nxt)
            if k not in seen:
                seen[k] = nxt
                elems_mat.append(nxt)
                frontier.append(nxt)

    keys = [mat_key(m) for m in elems_mat]
    key_to_mat = dict(zip(keys, elems_mat))
    return build_group_from_table(
        name,
        keys,
        lambda ka, kb: mat_key(mat_mul(key_to_mat[ka], key_to_mat[kb])),
    )


def build_delta54() -> FiniteGroup:
    """ Principal SU(3) subgroup Delta(54) ~= (Z_3 x Z_3) \\rtimes S_3 of order 54."""
    import cmath
    import math

    w = cmath.exp(2j * math.pi / 3)
    P = ((0j, 1 + 0j, 0j), (0j, 0j, 1 + 0j), (1 + 0j, 0j, 0j))
    Q = ((1 + 0j, 0j, 0j), (0j, w, 0j), (0j, 0j, w * w))
    R = ((-1 + 0j, 0j, 0j), (0j, 0j, -1 + 0j), (0j, -1 + 0j, 0j))
    return _build_su3_matrix_group("Delta(54)", [P, Q, R])


def build_sigma108() -> FiniteGroup:
    """SU(3) subgroup Sigma(36x3) of order 108."""
    import cmath
    import math

    w = cmath.exp(2j * math.pi / 3)
    is3 = 1.0 / (1j * math.sqrt(3))
    P = ((0j, 1 + 0j, 0j), (0j, 0j, 1 + 0j), (1 + 0j, 0j, 0j))
    Q = ((1 + 0j, 0j, 0j), (0j, w, 0j), (0j, 0j, w * w))
    V = ((is3, is3, is3), (is3, is3 * w, is3 * w * w), (is3, is3 * w * w, is3 * w))
    return _build_su3_matrix_group("Sigma(36x3)", [P, Q, V])


def build_sigma648() -> FiniteGroup:
    """Full Hessian SU(3) subgroup Sigma(216x3) of order 648 (triple cover of Sigma(216))."""
    import cmath
    import math

    w = cmath.exp(2j * math.pi / 3)
    eps = cmath.exp(2j * math.pi / 9)
    is3 = 1.0 / (1j * math.sqrt(3))
    P = ((0j, 1 + 0j, 0j), (0j, 0j, 1 + 0j), (1 + 0j, 0j, 0j))
    Q = ((1 + 0j, 0j, 0j), (0j, w, 0j), (0j, 0j, w * w))
    V = ((is3, is3, is3), (is3, is3 * w, is3 * w * w), (is3, is3 * w * w, is3 * w))
    D = ((eps, 0j, 0j), (0j, eps, 0j), (0j, 0j, eps**7))
    return _build_su3_matrix_group("Sigma(216x3)", [P, Q, V, D])

